export function getBulkSeedPapers(): AcademicPaper[] {
  let raw: Array<Record<string, any>> = [];
  try {
    raw = JSON.parse(fs.readFileSync(new URL('./bulkRaw.json', import.meta.url), 'utf8'));
  } catch {
    return [];
  }
  const out: AcademicPaper[] = [];
  const FALLBACK_AFFILIATIONS: Record<number, string[]> = {
    2: ['Stanford University'],
    15: ['Stanford University', 'UC Berkeley', 'Toyota Research Institute', 'Google DeepMind'],
    16: ['Physical Intelligence'],
    17: ['Physical Intelligence'],
    24: ['Zep AI'],
  };
  for (const e of ENTRIES) {
    const r = raw[e.idx];
    if (!r) continue;
    const sid = String(r.openAlexId).split('/').pop();
    const resolvedAffs = r.affiliations?.length ? r.affiliations : (FALLBACK_AFFILIATIONS[e.idx] || []);
    out.push({
      id: `oa-${sid}`,
      openAlexId: r.openAlexId,
      title: r.title,
      titleZh: e.titleZh,
      authors: r.authors,
      affiliations: resolvedAffs,
      journal: e.venue || r.journal,
      journalShort: e.short,
      journalRank: '',
      domain: e.domain,
      topics: e.topics,
      publishedDate: r.date,
      syncedAt: `${r.date}T08:00:00Z`,
      doi: r.doi,
      url: r.doi ? `https://doi.org/${r.doi}` : r.openAlexId,
      sourceOrigin: 'curated_real',
      abstractOriginal: r.abstract,
      digestSummary: e.digest,
      tags: e.tags,
      citedByCount: r.cited || 0,
      citations: (r.citations || []).map((c: any) => ({
        id: c.id,
        title: c.title,
        year: c.year,
        venue: c.venue,
        doi: c.doi,
        url: c.url,
        citedByCount: c.citedByCount,
        relation: c.relation,
      })),
      readingStatus: 'unread',
      isBookmarked: false,
      anatomy: {
        background: e.background,
        problem: e.problem,
        currentStatus: e.status,
        limitationsOfPriorWork: e.limitations,
        proposedMethod: e.method,
        architectureModules: e.modules,
        experimentalValidation: e.experiment,
        dataset: {
          sourceType: e.dsType,
          names: e.dsNames,
          scale: '',
          modalities: [],
          constructionSteps: [],
          summary: e.dsSummary,
        },
        comparisonMetrics: {
          hasQuantitativeData: false,
          metricNames: e.cmpCols || [],
          primaryMetric: e.cmpCols?.[0] || '',
          unit: '',
          rows: e.cmpRows || [],
        },
        ablationStudy: { hasQuantitativeData: false, metricName: '', unit: '', fullModelScore: '', items: [], summary: '' },
        conclusion: e.conclusion,
        futureAndLimitations: {
          paperLimitations: e.paperLimits,
          futureDirections: e.future,
        },
      },
      comments: [],
    });
  }
  return out;
}
